#!/usr/bin/env python3
"""Map-aware draft model: nearest-neighbour composition choice from a composition tournament.

The draft has to pick for maps we have never seen, so it compares the new map with the training maps (the
same features the bot computes in draft.cpp) and picks the composition that did best on the most similar
ones, shrunk towards that composition's average at this team size (a single map's result is noisy).

usage:
  python3 tools/draft_model.py RESULT.json FEATURES.json [--k 5] [--prior 3] [--emit bots/_dev/src/draft_table.h]

RESULT.json   tools/draft_tournament.py output (per-map wins and gem margins per composition)
FEATURES.json one record per map, from a LEGEND_FEATURES build of the bot (see docs/FEEDBACK_LOOP.md)

Prints leave-one-map-out cross-validation: the held-out win rate of the model's choice against always
playing the best composition for the team size, and the oracle (best per map, an upper bound).
"""
import argparse, json, math

FEATURES = ['log_area', 'groups', 'multi_f', 'elk_f', 'mono', 'wolf_f', 'gem_f', 'harmless_f', 'dist_n', 'holes_f', 'altars']
TEAM_PENALTY = 3.0


def vec(f):
    g = max(1.0, f['groups'])
    area = max(1.0, f['area'])
    return [math.log(area), f['groups'], f['multi'] / g, f['elk'] / g, 1.0 if f['mono'] > 0 else 0.0, f['wolf'] / g,
            f['gem_groups'] / g, f['harmless'] / g, f['mean_dist'] / math.sqrt(area), f['holes'] / area, f['altars']]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('result'); ap.add_argument('features')
    ap.add_argument('--k', type=int, default=5)
    ap.add_argument('--prior', type=float, default=3.0, help='weight of the team-size average, in neighbours')
    ap.add_argument('--gd', type=float, default=0.5, help='weight of the gem margin in the per-map score')
    ap.add_argument('--emit')
    args = ap.parse_args()
    res = json.load(open(args.result))
    comps = list(res['comps'])
    n_games = res.get('games_per_map', 2 * (len(comps) - 1))
    feats = {f['map']: f for f in json.load(open(args.features))}
    maps = sorted(m for m in res['per_map'] if m in feats)
    missing = sorted(set(res['per_map']) - set(feats))
    if missing:
        print('no features for', missing)
    wr = {m: [res['per_map'][m].get(c, 0) / n_games for c in comps] for m in maps}
    gd = {m: [res.get('per_map_gd', {}).get(m, {}).get(c, 0) / n_games / 1000.0 for c in comps] for m in maps}
    score = {m: [(1 - args.gd) * wr[m][i] + args.gd * (0.5 + 0.5 * max(-1.0, min(1.0, gd[m][i]))) for i in range(len(comps))] for m in maps}
    team = {m: int(feats[m]['team']) for m in maps}
    X = {m: vec(feats[m]) for m in maps}
    mean = [sum(X[m][j] for m in maps) / len(maps) for j in range(len(FEATURES))]
    sd = [max(1e-6, math.sqrt(sum((X[m][j] - mean[j]) ** 2 for m in maps) / len(maps))) for j in range(len(FEATURES))]
    Z = {m: [(X[m][j] - mean[j]) / sd[j] for j in range(len(FEATURES))] for m in maps}

    def choose(target, train, k=args.k, prior=args.prior):
        same = [m for m in train if team[m] == team[target]] or train
        base = [sum(score[m][i] for m in same) / len(same) for i in range(len(comps))]
        d = sorted(train, key=lambda m: math.dist(Z[m], Z[target]) + TEAM_PENALTY * abs(team[m] - team[target]))[:k]
        val = [(prior * base[i] + sum(score[m][i] for m in d)) / (prior + len(d)) for i in range(len(comps))]
        return max(range(len(comps)), key=lambda i: val[i]), max(range(len(comps)), key=lambda i: base[i])

    for k in (0, 3, 5, 8):
        for prior in (1.0, 3.0, 6.0):
            if k == 0 and prior != 3.0:
                continue
            tot_m = tot_b = tot_o = 0.0
            for m in maps:
                train = [x for x in maps if x != m]
                cm, cb = choose(m, train, k=k, prior=prior)
                tot_m += wr[m][cm]; tot_b += wr[m][cb]; tot_o += max(wr[m])
            n = len(maps)
            print(f'k={k} prior={prior:3.0f}  held-out win rate: model {tot_m / n:.3f}  team-size best {tot_b / n:.3f}  oracle {tot_o / n:.3f}')
    print('\nper-composition mean win rate by team size:')
    for t in (3, 4, 5):
        ms = [m for m in maps if team[m] == t]
        if ms:
            print(f'  team {t} ({len(ms)} maps): ' + '  '.join(f'{c}:{sum(wr[m][i] for m in ms) / len(ms):.3f}' for i, c in enumerate(comps)))
    if args.emit:
        names = {0: 'ryth', 1: 'vesper_vale', 2: 'vendetta', 3: 'cassi_and_issac', 4: 'stellar', 5: 'prism', 6: 'marcella', 7: 'willow', 8: 'ren', 9: 'varg', 10: 'tavi'}
        L = ['// Generated by tools/draft_model.py from a composition tournament; do not edit by hand.',
             '// Training maps: draft features (draft.cpp) and each composition\'s score on that map.',
             '#pragma once', '#include <array>', '#include <cambc.h>', '', 'namespace draft_table', '{',
             f'constexpr int NCOMP = {len(comps)};', f'constexpr int NF = {len(FEATURES)};',
             f'constexpr int K = {args.k};', f'constexpr float PRIOR = {args.prior:.2f}f;', f'constexpr float TEAM_PENALTY = {TEAM_PENALTY:.2f}f;',
             'struct Comp', '{', '\tconst char* name;', '\tstd::array<bc::champion_draft, 5> picks;', '};',
             'constexpr std::array<Comp, NCOMP> COMPS{ {']
        for c in comps:
            picks = ', '.join(f'bc::champion_draft::{names[int(x)]}' for x in res['comps'][c].split(','))
            L.append(f'\t{{ "{c}", {{ {picks} }} }},')
        L += ['} };', '// ' + ', '.join(FEATURES),
              'constexpr std::array<float, NF> MEAN{ ' + ', '.join(f'{v:.5f}f' for v in mean) + ' };',
              'constexpr std::array<float, NF> SD{ ' + ', '.join(f'{v:.5f}f' for v in sd) + ' };',
              'struct Row', '{', '\tint team;', '\tstd::array<float, NF> z;', '\tstd::array<float, NCOMP> score;', '};',
              f'constexpr std::array<Row, {len(maps)}> ROWS{{ {{']
        for m in maps:
            L.append(f'\t{{ {team[m]}, {{ ' + ', '.join(f'{v:.3f}f' for v in Z[m]) + ' }, { ' + ', '.join(f'{v:.3f}f' for v in score[m]) + f' }} }}, // {m}')
        L += ['} };', '} // namespace draft_table', '']
        open(args.emit, 'w').write('\n'.join(L))
        print('wrote', args.emit)


if __name__ == '__main__':
    main()
