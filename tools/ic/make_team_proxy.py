#!/usr/bin/env python3
"""A ladder team's drafts on GOD's brain: bots/<name> = bots/<base>/src (GOD v10 by default) with the team's own draft forced on every
official map where the ladder data has it (its most frequent roster there, picks in its order), GOD's draft elsewhere. A sparring
partner that drafts like the team; the play stays GOD's (our code family), so it measures the draft half of the match-up only.

    python3 -I tools/ic/make_team_proxy.py --team 1890540d-1ffc-4847-adbf-d0d08772f268 --name _px_ic [--base god]
        [--lists experiments/ladder_oct24/mapintel_20261024_0836]

Data: <lists>/lists/<team id 8>.jsonl (the team's recent ranked matches, tools/mapintel/ladder_fetch.py) and <lists>/matches_current.jsonl;
map fingerprints from tools/mapintel/data/battery_rosters.json. Prints the table it forced (map, games, share of the roster, picks)."""
import argparse
import collections
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PICK_NAMES = ["Ryth", "Vesper Vale", "Vendetta", "Cassi & Issac", "Stellar", "Prism", "Marcella", "Willow", "Ren", "Varg", "Tavi", "Heart of Ruin"]


def team_rosters(lists_dir, team):
	seen, games = set(), collections.defaultdict(collections.Counter)
	paths = [os.path.join(lists_dir, "lists", team[:8] + ".jsonl"), os.path.join(lists_dir, "matches_current.jsonl")]
	for p in paths:
		if not os.path.exists(p):
			continue
		for line in open(p):
			m = json.loads(line)
			if m["matchId"] in seen or m.get("status") != "finished":
				continue
			seen.add(m["matchId"])
			for t in m["teams"]:
				if t["teamId"] == team:
					games[m["map"].replace("_", "-")][tuple(t["draftPicks"])] += 1
	return games


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--team", required=True)
	ap.add_argument("--name", required=True)
	ap.add_argument("--base", default="god")
	ap.add_argument("--lists", default=os.path.join(ROOT, "experiments/ladder_oct24/mapintel_20261024_0836"))
	a = ap.parse_args()
	games = team_rosters(a.lists, a.team)
	if not games:
		sys.exit(f"no matches of team {a.team} in {a.lists}")
	R = json.load(open(os.path.join(ROOT, "tools/mapintel/data/battery_rosters.json")))
	lines = []
	for n in sorted(R["maps"]):
		c = games.get(n)
		if not c:
			print(f"{n}: no games, GOD's draft")
			continue
		picks, k = c.most_common(1)[0]
		tot = sum(c.values())
		print(f"{n}: {tot} games, {k}/{tot} with " + ", ".join(PICK_NAMES[p] for p in picks))
		lines.append(f"\t{{ 0x{R['maps'][n]['fingerprint']}ull, {len(picks)}, {{ {', '.join(map(str, list(picks) + [0] * (5 - len(picks))))} }} }}, /* {n} */")
	d = os.path.join(ROOT, "bots", a.name)
	shutil.rmtree(d, ignore_errors=True)
	os.makedirs(d)
	src = os.path.join(d, "src")
	shutil.copytree(os.path.join(ROOT, "bots", a.base, "src"), src)
	gi = os.path.join(ROOT, "bots", "legend", ".gitignore")
	if os.path.exists(gi):
		shutil.copy(gi, d)
	os.makedirs(os.path.join(src, "mapintel"), exist_ok=True)
	for h in ("force_roster.h", "fingerprint.h"):
		shutil.copy(os.path.join(ROOT, "tools", "mapintel", "cpp", "mapintel", h), os.path.join(src, "mapintel", h))
	open(os.path.join(src, "mapintel", "mi_roster.h"), "w").write(
		f"// generated by tools/ic/make_team_proxy.py: team {a.team}'s most frequent roster per map\n#define MI_ROSTER_ENTRIES \\\n" + " \\\n".join(lines) + "\n")
	p = os.path.join(src, "draft.cpp")
	s = open(p).read()
	old_inc, old_fn = '#include "params.h"\n', "void play_draft_pick()\n{\n"
	if s.count(old_inc) < 1 or s.count(old_fn) != 1:
		sys.exit("draft.cpp changed: the forced-roster hook does not apply")
	s = s.replace(old_inc, old_inc + '#include "mapintel/force_roster.h"\n', 1)
	s = s.replace(old_fn, old_fn + "\tif (const int fp = mapintel::forced_pick(); fp >= 0)\n\t{\n\t\tnote_pick(static_cast<D>(fp));\n\t\treturn;\n\t}\n", 1)
	open(p, "w").write(s)
	r = subprocess.run(["cambc", "build", a.name, "--release"], cwd=ROOT, capture_output=True, text=True)
	if r.returncode != 0:
		sys.exit("build failed:\n" + (r.stdout + r.stderr)[-3000:])
	print(f"bots/{a.name} ready: bots/{a.base} with the team's roster forced on {len(lines)} maps")


if __name__ == "__main__":
	main()
