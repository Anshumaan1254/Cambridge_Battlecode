static void line(const std::string& s)
{
	const std::string t = s + "\n";
	std::fputs(t.c_str(), stdout);
	std::fflush(stdout);
}

static const char* HX = "0123456789abcdef";
static std::string hex(const std::uint8_t* p, int n)
{
	std::string s;
	s.reserve(static_cast<std::size_t>(2 * n));
	for (int k = 0; k < n; ++k)
		s += HX[p[k] >> 4], s += HX[p[k] & 15];
	return s;
}
static std::string fnv(const std::uint8_t* p, int n)
{
	std::uint64_t h = 1469598103934665603ull;
	for (int k = 0; k < n; ++k)
		h = (h ^ p[k]) * 1099511628211ull;
	std::uint8_t b[8];
	for (int k = 0; k < 8; ++k)
		b[k] = static_cast<std::uint8_t>(h >> (56 - 8 * k));
	return hex(b, 8);
}

struct State
{
	std::optional<mi::MapView> V;
	std::optional<mi::Features> F;
	std::optional<mi::Compact> C, CE;
	mi::Plans P;
	std::optional<mi::Kits13> K;
	mi::Draft2 D;
	mi::OwnResult own;
	bool have_own = false, nav_done = false;
	mi::NavWork navw;
	mi::BankBox BB;
	mi::OwnRecompute orc;
	std::uint8_t dl_open[16]{};
	bool have_dl_open = false;
	int dl_source = 0;
	long long last_write = 0;
	bool own_rc_done = false;
	long long own_rc_fuel = 0;
	int own_rc_turns = 0;
	long long nav_fuel = 0;
	std::vector<int> picks;
	int ts = 0, side = 0, known = -1, kteam = -1, arch = 255, nrank = 0, nbo = 0, enemy_seen = 0;
	std::uint64_t fp = 0;
	int rank[16]{}, bank_ord[8]{}, rally[8]{}, nrally = 0;
	std::array<std::uint8_t, mi::NAV_SIZE> nav{};
};

static void diag(State& S, int t, int k, long long v)
{
	const int o = 436 + 12 * (t - 1) + 2 * k;
	const long long u = std::min<long long>(65535, std::max<long long>(0, v / 16));
	S.D.img.b[static_cast<std::size_t>(o)] = static_cast<std::uint8_t>(u & 255), S.D.img.b[static_cast<std::size_t>(o + 1)] = static_cast<std::uint8_t>(u >> 8);
}
static long long fuel() { return static_cast<long long>(bc::fuel_remaining()); }
#ifdef MI_DM2_STAGES
#define STAGE(n) line(std::string("MI S ") + (n) + " " + std::to_string(fuel()) + " mem " + std::to_string(__builtin_wasm_memory_size(0)))
#else
#define STAGE(n)
#endif

// test diagnostics of turn 1's parts at 1002 + 2k (u16, units of 16; the full write keeps bytes 1000-1023, a real bot leaves them):
// 0 kits of the 13 designs, 1 bank order + rally tiles, 2 the M block, 3 TEAM + CODE, 4 NAV, 5 OWN, 6 the enemy Compact + ENEMY,
// 7 the turn NAV ran on (8..: the turn's left fuel after it)
static void part(State& S, int k, long long v)
{
	const int o = 1002 + 2 * k;
	const long long u = std::min<long long>(65535, std::max<long long>(0, v / 16));
	S.D.img.b[static_cast<std::size_t>(o)] = static_cast<std::uint8_t>(u & 255), S.D.img.b[static_cast<std::size_t>(o + 1)] = static_cast<std::uint8_t>(u >> 8);
}

static void rows_of(State& S, int pick)
{
	int b[2];
	const int nb = mi::pick_bodies(pick, b);
	for (int j = 0; j < nb; ++j)
		S.C->row(b[j]);
}

static int types_of(const State& S, int out[mi::NSLOT]) { return mi::roster_types(S.picks.data(), static_cast<int>(S.picks.size()), out); }

static void put_team(State& S)
{
	int types[mi::NSLOT];
	const int n = types_of(S, types);
	S.D.img.put(mi::BK_TEAM, mi::build_team(S.P, types, n, S.have_own ? &S.own : nullptr, S.K->p.capture_mode));
}

static void put_code(State& S) { S.D.img.put(mi::BK_CODE, mi::build_code(S.rally, S.nrally, S.have_own ? &S.own : nullptr, S.bank_ord, S.nbo)); }

static bool run_own(State& S, long long& cost)
{
	int types[mi::NSLOT];
	const int n = types_of(S, types);
	const long long a = fuel();
	const bool ran = S.D.run(mi::BK_OWN, [&] {
		const auto gs = mi::own_groups(*S.C, *S.V, S.K->p);
		S.own = mi::build_own(gs, types, n, *S.K);
		S.have_own = true;
		S.D.img.put(mi::BK_OWN, S.own.b);
	}, mi::OWN_EST);
	cost = ran ? a - fuel() : 0;
	if (ran)
		S.D.img.b[496] |= static_cast<std::uint8_t>(1u << (S.D.turn - 1));
	return ran;
}

// NAV: the map's hazards (roster-free). A known map copies known_maps.h's block (free); an unknown map resumes the NavWork every draft
// turn down to a fuel floor and writes the block when it is complete. MI_DM2_NAV_ALWAYS (the test's roster-0 build) computes it on
// known maps too, so it can be compared with the table. Byte 498: 1 equal to the table, 0 differs, 255 not compared; 1016: the turn
// it was complete; 1017: 1 computed, 2 copied.
static void run_nav(State& S, long long floor)
{
	if (S.nav_done)
		return;
	mi::NavInput in;
	mi::nav_anchor_groups(*S.C, std::span<const int>(S.rank, static_cast<std::size_t>(S.nrank)), in.anchor_groups);
	for (int k = 0; k < 3; ++k)
		in.altars[k] = k < S.nbo ? S.bank_ord[k] : -1;
#if defined(MI_HAS_TABLE) && !defined(MI_DM2_NAV_ALWAYS)
	if (S.known >= 0)
	{
		S.nav = mi::nav_from_table(mi::KNOWN[S.known].nav + 64 * S.kteam);
		S.D.img.put(mi::BK_NAV, S.nav);
		S.nav_done = true, S.D.img.b[1016] = static_cast<std::uint8_t>(S.D.turn), S.D.img.b[1017] = 2;
		return;
	}
#endif
	in.floor = floor;
	const long long a = fuel();
	const bool done = mi::nav_resume(S.navw, *S.V, *S.C, in);
	S.nav_fuel += a - fuel();
	if (!done)
		return;
	S.nav = mi::nav_block(S.navw, *S.V, *S.C, in);
	S.D.img.put(mi::BK_NAV, S.nav);
	S.nav_done = true;
	part(S, 4, S.nav_fuel);
	S.D.img.b[1016] = static_cast<std::uint8_t>(S.D.turn), S.D.img.b[1017] = 1;
	std::uint8_t eq = 255;
#ifdef MI_HAS_TABLE
	if (S.known >= 0)
	{
		const auto tb = mi::nav_from_table(mi::KNOWN[S.known].nav + 64 * S.kteam);
		eq = 1;
		for (int k = 0; k < 61; ++k)
			eq = tb[static_cast<std::size_t>(k)] == S.nav[static_cast<std::size_t>(k)] ? eq : 0;
	}
#endif
	S.D.img.b[498] = eq;
}

// L (mapintel's DL outputs): turn 1 the opening ranking (a known map copies known_maps.h's; an unknown map computes it with dl_weights.h
// when the guard allows: the inputs and the scores, ~150k); the last turn the routes (known maps: the table). Byte 1018: the L block's
// fuel on its last write / 16 (test).
static void dl_opening(State& S)
{
#if defined(MI_HAS_TABLE) && defined(MAPINTEL_DL_TABLES)
	if (S.known >= 0 && mi::KNOWN[S.known].dl_open)
	{
		std::memcpy(S.dl_open, mi::KNOWN[S.known].dl_open + 16 * S.kteam, 16);
		S.have_dl_open = true, S.dl_source = 2;
		return;
	}
#endif
#ifdef MAPINTEL_DL_OPENING
	if (S.known >= 0)
		return; // a known map without the table: nothing to copy (the bot computes nothing a table should hold)
	S.D.run(mi::BK_DL, [&] {
		const auto I = mi::dl_inputs(*S.C, *S.V, *S.F);
		const auto sc = mi::dl_opening_scores(I);
		std::vector<int> gs;
		for (int g = 0; g < static_cast<int>(sc.size()); ++g)
			if (sc[static_cast<std::size_t>(g)] > -1e299)
				gs.push_back(g);
		std::sort(gs.begin(), gs.end(), [&](int a, int b) { return sc[static_cast<std::size_t>(a)] != sc[static_cast<std::size_t>(b)] ? sc[static_cast<std::size_t>(a)] > sc[static_cast<std::size_t>(b)] : a < b; });
		for (int k = 0; k < 16; ++k)
			S.dl_open[k] = k < static_cast<int>(gs.size()) ? static_cast<std::uint8_t>(gs[static_cast<std::size_t>(k)]) : 255;
		S.have_dl_open = true, S.dl_source = 1;
	}, 160000);
#endif
}

static void put_dl(State& S, bool routes)
{
	const long long a = fuel();
	const std::uint8_t* nx = nullptr;
	int G = 0, split = 0, r0 = 0, r1 = 0;
#if defined(MI_HAS_TABLE) && defined(MAPINTEL_DL_TABLES)
	split = mi::DL_TABLE_SPLIT, r0 = mi::DL_TABLE_ROUNDS[0], r1 = mi::DL_TABLE_ROUNDS[1];
	if (routes && S.known >= 0 && mi::KNOWN[S.known].dl_next)
		G = mi::KNOWN[S.known].ngroups, nx = mi::KNOWN[S.known].dl_next + 2 * (S.kteam * 2 * 13 * G);
#endif
	if (!S.have_dl_open && !nx)
		return;
	int types[mi::NSLOT];
	const int n = types_of(S, types);
	if (nx && S.dl_source == 0)
		S.dl_source = 2;
	S.D.img.put(mi::BK_DL, mi::build_dl(S.have_dl_open ? S.dl_open : nullptr, S.dl_source, nx, G, types, n, &S.P, split, r0, r1));
	const long long u = std::min<long long>(255, (a - fuel()) / 16);
	S.D.img.b[1018] = static_cast<std::uint8_t>(u);
}

static long long run_enemy(State& S)
{
	std::vector<int> ep;
	for (const auto d : bc::draft::current_draft(bc::team::enemy))
		ep.push_back(static_cast<int>(d));
	const long long a = fuel();
	const bool ran = S.D.run(mi::BK_ENEMY, [&] {
		if (!S.CE)
			S.CE.emplace(*S.C, 1), S.BB.build(*S.V, 1); // the enemy side's tables: our Compact mirrored (no second group preparation)
		S.D.img.put(mi::BK_ENEMY, mi::build_enemy(*S.CE, S.BB, *S.K, ep.data(), static_cast<int>(ep.size())));
		S.enemy_seen = static_cast<int>(ep.size());
	}, S.CE ? mi::ENEMY_EST : mi::ENEMY_EST + mi::CE_EST);
	S.D.img.b[497] = static_cast<std::uint8_t>(S.enemy_seen);
	return ran ? a - fuel() : 0;
}

static void put_map(State& S)
{
	S.D.img.put(mi::BK_MAP, mi::dmem_pack(S.P, S.fp, S.ts, S.known >= 0, S.arch));
}

static void draft_turn(State& S)
{
	STAGE("start");
	S.D.begin();
	const int t = S.D.turn;
	const long long f0 = fuel();
	// ---- the pick first
	if (t == 1)
	{
		S.ts = mi::team_size_now();
		int lo[2] = { 1 << 30, 1 << 30 };
		const bc::team side[2] = { bc::team::ally, bc::team::enemy };
		for (int k = 0; k < 2; ++k)
			for (const auto p : bc::map::spawn_region(side[k]).positions())
				lo[k] = std::min(lo[k], p.y * bc::map::width() + p.x);
		S.side = lo[0] < lo[1] ? 0 : 1;
	}
	const int* R = MI_DM2_ROSTERS[(MI_DM2_R + S.side) % 3];
	const int pick = R[std::min<int>(static_cast<int>(S.picks.size()), 4)];
	bc::draft::pick(static_cast<bc::champion_draft>(pick));
	S.picks.push_back(pick);
	STAGE("pick");
	const long long f1 = fuel();
	const bool last = S.ts > 0 && static_cast<int>(S.picks.size()) >= S.ts;
	diag(S, t, 0, f0), diag(S, t, 1, f1);
	long long own_cost = 0, other = 0;
	if (t == 1)
	{
		S.V.emplace(mi::load_view(S.ts));
		S.fp = mi::fingerprint(*S.V);
		S.F.emplace(mi::compute_features(*S.V));
		S.C.emplace(*S.V, *S.F);
		S.P = mi::base_plans(*S.C, *S.V, *S.F);
		rows_of(S, pick);
#ifdef MI_HAS_TABLE
		S.known = mi::find_known(S.fp);
		if (S.known >= 0)
			S.kteam = mi::known_team(*S.V, mi::KNOWN[S.known]);
#endif
#ifdef MI_HAS_WEIGHTS
		{
			double z[mi::MW_NF];
			mi::zfeat(*S.F, z);
			S.arch = mi::archetype_of(z);
		}
#ifdef MAPINTEL_FIRST_SCORES
		{
			const auto sc = mi::first_scores(*S.C, *S.V, *S.F);
			std::vector<int> gs;
			for (int g = 0; g < static_cast<int>(sc.size()); ++g)
				if (sc[static_cast<std::size_t>(g)] > -1e299)
					gs.push_back(g);
			std::sort(gs.begin(), gs.end(), [&](int a, int b) { return sc[static_cast<std::size_t>(a)] != sc[static_cast<std::size_t>(b)] ? sc[static_cast<std::size_t>(a)] > sc[static_cast<std::size_t>(b)] : a < b; });
			for (int k = 0; k < 16 && k < static_cast<int>(gs.size()); ++k)
				S.rank[S.nrank++] = gs[static_cast<std::size_t>(k)];
		}
#endif
#endif
		const long long f2 = fuel();
		diag(S, t, 2, f2);
		// ---- v2 additions of turn 1, cheapest and most needed first; every optional block under the guard
		long long a = fuel();
		S.K.emplace(mi::kits13_from_sdk());
		part(S, 0, a - fuel()), a = fuel();
		S.nbo = mi::bank_order(*S.C, S.P, S.bank_ord);
		S.nrally = mi::rally_tiles(*S.C, *S.V, S.P, S.bank_ord, S.nbo, S.rally);
		part(S, 1, a - fuel()), a = fuel();
		put_map(S);
		part(S, 2, a - fuel()), a = fuel();
		put_team(S);
		put_code(S);
		part(S, 3, a - fuel());
		run_nav(S, 30000);
		run_own(S, own_cost);
		part(S, 5, own_cost);
		put_team(S);
		put_code(S);
		other = run_enemy(S);
		part(S, 6, other);
		dl_opening(S);
		put_dl(S, false);
	}
	else
	{
		rows_of(S, pick);
		if (last)
		{
			S.C->plan1(std::span<const int>(S.picks.data(), S.picks.size()), S.P, std::span<const int>(S.rank, static_cast<std::size_t>(S.nrank)));
			put_map(S);
		}
		diag(S, t, 2, fuel());
		if (last)
		{
			int types[mi::NSLOT];
			const int n = types_of(S, types);
			const long long bc0 = fuel();
			int bb, rp;
			mi::econ_body(bb, rp);
			S.D.img.put(mi::BK_BODY, mi::build_body(types, n, *S.K, S.P, bb, rp));
			std::vector<int> ep;
			for (const auto d : bc::draft::current_draft(bc::team::enemy))
				ep.push_back(static_cast<int>(d));
			S.D.img.put(mi::BK_CONT, mi::build_cont(*S.K, ep.data(), static_cast<int>(ep.size()), types, n));
			S.D.img.b[503] = static_cast<std::uint8_t>(ep.size()); // test: the enemy picks CONT saw
			S.D.img.b[1019] = static_cast<std::uint8_t>(std::min<long long>(255, (bc0 - fuel()) / 64)); // test: BODY + CONT / 64
			put_dl(S, true);
		}
		STAGE("rows");
		run_own(S, own_cost);
		STAGE("own");
		put_team(S);
		STAGE("team");
		put_code(S);
		STAGE("code");
		other = run_enemy(S);
		STAGE("enemy");
		run_nav(S, 12000);
	}
	diag(S, t, 3, own_cost), diag(S, t, 4, other), diag(S, t, 5, fuel());
	S.D.img.b[499] = static_cast<std::uint8_t>(S.side), S.D.img.b[500] = static_cast<std::uint8_t>(S.ts), S.D.img.b[501] = S.known >= 0 ? 1 : 0;
	if (last)
	{
		S.D.img.b[1000] = 0xAB;
		S.D.img.b[1020] = static_cast<std::uint8_t>(std::min<long long>(255, S.last_write / 64)); // test: the previous turn's write / 64
		S.D.write(true, false);
		S.D.img.b[1000] = 0;
		bc::draft_memory = std::span<const std::uint8_t>(S.D.img.b.data(), 1000); // the shorter write
	}
	else
	{
		const long long w0 = fuel();
		S.D.write(false, t == 1);
		S.last_write = w0 - fuel();
	}
	STAGE("write");
}

// The agreement with the live bytes (teamplan/live.h, docs/DRAFT_MEMORY.md 5.1, 5.5, 6): this body's live slot (live_init, from the
// engine's ally list) and the TEAM block's slot; the places (groups = the M block's count, altars = the map's, rallies = CODE's
// valid tiles): every CODE rally tile and altar id must have a place code that maps back to it. Prints "<live slot> <team slot>
// <live n> <TEAM n> <places ok> <groups> <altars> <rallies>".
static std::string live_check(const std::uint8_t* team)
{
	teamplan::LiveState L;
	teamplan::live_init(L);
	mi::Reader r;
	r.load();
	const std::uint8_t* code = r.block('K', 1);
	const std::uint8_t* mb = r.block('M', 1);
	const auto my = static_cast<int>(bc::self().champion_name());
	teamplan::Places P;
	P.groups = mb ? mb[13] : 0;
	P.altars = static_cast<int>(bc::map::altars().count());
	int ok = code && mb ? 1 : 0;
	for (int k = 0; code && k < 8; ++k)
		if ((code[2 * k] | code[2 * k + 1] << 8) != 0xFFFF)
			P.rallies = k + 1;
	for (int k = 0; ok && k < P.rallies; ++k)
	{
		int idx = -1;
		const int c = teamplan::place_code(P, teamplan::PLACE_RALLY, k);
		ok &= c == teamplan::NO_PLACE || (teamplan::place_kind(P, c, &idx) == teamplan::PLACE_RALLY && idx == k);
	}
	for (int k = 0; ok && k < 8; ++k)
		if (code[24 + k] != 255)
		{
			int idx = -1;
			const int c = teamplan::place_code(P, teamplan::PLACE_ALTAR, code[24 + k]);
			ok &= code[24 + k] < P.altars && (c == teamplan::NO_PLACE || (teamplan::place_kind(P, c, &idx) == teamplan::PLACE_ALTAR && idx == code[24 + k]));
		}
	for (int k = 0; ok && k < 8; ++k)
		if (code[16 + k] != 255)
			ok &= code[16 + k] < P.groups;
	return std::to_string(L.slot) + " " + std::to_string(team ? mi::team_slot(team, my) : -1) + " " + std::to_string(L.n) + " " +
		   std::to_string(team ? mi::team_size_of(team) : -1) + " " + std::to_string(ok) + " " + std::to_string(P.groups) + " " +
		   std::to_string(P.altars) + " " + std::to_string(P.rallies);
}

static void champion_turn(State& S, int gt)
{
	const auto my = static_cast<int>(bc::self().champion_name());
	mi::Reader r;
	r.load();
	const std::uint8_t* team = r.block('T', 1);
	const int n = team ? mi::team_size_of(team) : 0;
	const bool lowest = team && team[4] == my;
	if (gt == 1)
	{
		mi::Block B;
		const bool v1 = mi::dmem_get(B);
		const auto* p = reinterpret_cast<const std::uint8_t*>(bc::draft_memory.data());
		const int sz = static_cast<int>(bc::draft_memory.size());
		line("MI C1 slot " + std::to_string(team ? mi::team_slot(team, my) : -1) + " type " + std::to_string(my) + " n " + std::to_string(n) + " hash " +
			 (sz >= 1024 ? fnv(p, 1024) : std::string("short")) + " v1 " + std::to_string(v1 ? 1 : 0) + " v1hash " + (v1 ? fnv(B.b.data(), mi::DMEM_SIZE) : std::string("none")) +
			 " hdr " + std::to_string(r.ok ? 1 : 0) + " live " + live_check(team));
		if (lowest && sz >= 1024)
			line("MI IMG " + hex(p, 512)), line("MI P " + hex(p + 1000, 24));
	}
	else if (gt >= 2 && !S.own_rc_done)
	{
		// the in-game OWN recompute for the full roster, resumable over game turns (floor 20,000 for the rest of a real turn)
		const long long a = fuel();
		const bool done = S.orc.step(r, 20000);
		S.own_rc_fuel += a - fuel(), ++S.own_rc_turns;
		if (done || S.orc.failed)
		{
			S.own_rc_done = true;
			line("MI C2 type " + std::to_string(my) + " own " + (done ? fnv(S.orc.out.b.data(), mi::OWN_MAX) : std::string("none")) + " ok " +
				 std::to_string(done ? 1 : 0) + " fuel " + std::to_string(S.own_rc_fuel) + " turns " + std::to_string(S.own_rc_turns) + " n " +
				 std::to_string(S.orc.out.n));
		}
	}
	if (gt == 1 && lowest)
	{
		// six corrupted copies: per case the mask of the blocks the reader still finds (bit k = DM2_BLOCKS[k])
		std::string out = "MI C3";
		static std::array<std::uint8_t, 1024> b;
		const auto* p = reinterpret_cast<const std::uint8_t*>(bc::draft_memory.data());
		for (int cs = 0; cs < 6; ++cs)
		{
			std::memcpy(b.data(), p, 1024);
			auto reseal = [&] {
				unsigned s = 0;
				for (int i = 4; i < 100; ++i)
					s += b[static_cast<std::size_t>(i)];
				b[3] = static_cast<std::uint8_t>(s & 255);
			};
			if (cs == 0)
				b[116 + 3] ^= 0x5A; // OWN data: checksum mismatch
			else if (cs == 1)
				b[4 + 8 * mi::BK_BODY + 1] = 9, reseal(); // BODY version 9
			else if (cs == 2)
				b[0] = 0x55; // header magic
			else if (cs == 3)
				b[4 + 8 * mi::BK_CODE + 2] = 0xF0, b[4 + 8 * mi::BK_CODE + 3] = 3, reseal(); // CODE offset 1008: past the end
			else if (cs == 4)
				b[4 + 8 * mi::BK_ENEMY + 7] = 0, reseal(); // ENEMY not valid
			else
			{
				for (int i = 0; i < 8; ++i)
					b[static_cast<std::size_t>(4 + 8 * mi::BK_NAV + i)] = 0; // NAV missing
				reseal();
			}
			mi::Reader q;
			q.load(b.data(), b.size());
			unsigned mask = 0;
			for (int k = 0; k < 10; ++k)
				if (q.block(mi::DM2_BLOCKS[k].id, mi::DM2_BLOCKS[k].version))
					mask |= 1u << k;
			out += " " + std::to_string(mask);
		}
		line(out);
	}
}

int main()
{
	static State S; // static: the state is tens of KB and the wasm shadow stack is small (a stack overflow corrupts static data silently)
	int gt = 0;
	while (true)
	{
		try
		{
			if (bc::is_draft())
				draft_turn(S);
			else if (++gt <= 8)
				champion_turn(S, gt);
		}
		catch (const std::exception& e)
		{
			line(std::string("MI E ") + e.what());
		}
		catch (...)
		{
			line("MI E unknown");
		}
		bc::end_turn();
	}
}
