// Test bot of draft memory v2 (tools/mapintel/cpp/mapintel/dmem2.h; built as the git-ignored bots/_mi_dm2_<r> by
// tools/mapintel/test_dmem2.py, which also writes src/mi_dm2_roster.h). It drafts as a bot would: every draft turn picks FIRST (a roster
// from the generated header: team side 0 = the side whose lowest spawn tile is the lower one takes roster R, the other R + 1), then
// mapintel's work of that turn, then the v2 blocks under the fuel guard, then one whole-image write.
//   turn 1: view, fingerprint, features, Compact (ours and the enemy's), plans 2-4, the pick's rows, the table lookup, first_scores(),
//           the kits of all 13 designs, NAV (always computed here, as for an unknown map; compared with known_maps.h's copy), OWN for
//           the bodies picked so far (guarded), TEAM, CODE, ENEMY, the M block (plans 2-4), DEBUG; header flag minimal.
//   middle turns: the pick's rows, OWN (guarded), TEAM, CODE, ENEMY (guarded), DEBUG.
//   last turn: the pick's rows, plan 1, the M block with plan 1, BODY, CONT, TEAM, OWN for the final roster only under the guard,
//           CODE, ENEMY, DEBUG; flag final. Then the prefix test: the image is submitted with byte 1000 = 0xAB, then its first 1000
//           bytes again (a shorter write): the champions must read byte 1000 = 0xAB (the tail kept) and the rest unchanged.
// Test diagnostics in the free bytes 436-511 (a real bot leaves them free): per turn t (12 bytes at 436 + 12 (t - 1)): fuel at the
//   turn's start, after the pick, after mapintel's work, OWN's cost, NAV's (turn 1) or ENEMY's cost, fuel left before the write (all
//   uint16 in units of 16); 496 bit t-1 = OWN ran in turn t; 497 the enemy picks ENEMY last saw; 498 NAV equals known_maps.h's
//   (1 equal, 0 differs, 255 not compared); 499 our side; 500 team size; 501 bit 0 = known map; 502 spare; 503 the enemy picks CONT
//   saw. Bytes 1000-1023 (kept by the prefix write): 1000 the prefix marker, 1002-1015 turn 1's block costs (see part()), 1016-1017 NAV's, 1018 the L block's last
//   write / 16, 1019 BODY + CONT / 64, 1020 a draft write (DEBUG, seal, submit) / 64.
// Champions (no draft prints: stdout costs ~90 fuel a byte):
//   game turn 1: MI C1 slot <s> type <t> hash <FNV-1a 64 of the 1024 bytes> v1 <0|1 dmem_get> v1hash <FNV of the 352-byte block>
//                (the lowest body type only, also: MI IMG <hex of bytes 0-511>)
//   game turn 2: the in-game OWN recompute (always here, to test it on every map): MI C2 type <t> own <FNV of the 64 bytes> ok <0|1>
//                fuel <f>
//   game turn 3: the fallback cases (the lowest body type only): MI C3 <per case the found-block mask> on six corrupted copies
//   MI E <what> on any exception.
