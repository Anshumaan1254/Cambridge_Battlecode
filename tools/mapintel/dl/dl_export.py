#!/usr/bin/env python3
"""dl_weights.json (dl_train.py) -> tools/mapintel/cpp/mapintel/dl_weights.h, the in-bot part of step 7 (MAPAnalysis.md 5.7).

    python3 -I tools/mapintel/dl/dl_export.py [--weights experiments/results/mapintel/dl_model/dl_weights.json]
                                              [--out tools/mapintel/cpp/mapintel/dl_weights.h]

Only the models dl_train.py marked "export" (they beat the step-6 model on held-out maps) are written. The C++ uses the feature layout and
the summation order of dl_ref.py (float64, plain loops), so test_library.py can compare the engine with Python. Functions:
  dl_inputs(C, view, F)                       the group features and zfeat every group model uses: compute once per map, keep it
  dl_opening_scores(I)                        score per group (higher = taken earlier); unreached groups -1e300
  dl_next_scores(C, I, prev, type, round, &only)  score per group for a body of champion type `type` (cambc::champion_type) that
                                              last captured group `prev`, at game round `round`; only the groups in `only` when given
  dl_champion_values(F, out[12])              the draft value of each champion (draft ids) on this map, log-odds
Each defines MAPINTEL_DL_<NAME> so a bot can test for it."""
import argparse, hashlib, json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))


def arr(v):
	return "{ " + ", ".join(repr(float(x)) if not isinstance(x, int) else str(x) for x in v) + " }"


def model_block(name, m):
	sizes = [len(m["mean"])] + [len(b) for _, b in m["layers"]]
	W = [w for layer, _ in m["layers"] for row in layer for w in row]
	B = [b for _, bias in m["layers"] for b in bias]
	if max(sizes) > 64:
		raise SystemExit(f"{name}: a layer wider than 64")
	return [f"inline constexpr int DL_{name}_NL = {len(m['layers'])};",
			f"inline constexpr int DL_{name}_SZ[DL_{name}_NL + 1] = {arr(sizes)};",
			f"inline constexpr double DL_{name}_MEAN[{sizes[0]}] = {arr(m['mean'])};",
			f"inline constexpr double DL_{name}_STD[{sizes[0]}] = {arr(m['std'])};",
			f"inline constexpr double DL_{name}_W[{len(W)}] = {arr(W)};",
			f"inline constexpr double DL_{name}_B[{len(B)}] = {arr(B)};"]


def header(J, sha):
	L = ["// mapintel/dl_weights.h: GENERATED by tools/mapintel/dl/dl_export.py from dl_weights.json (tools/mapintel/dl/dl_train.py); do not",
		 "// edit (MAPAnalysis.md 5.7, step 7). LEARNED models: those the run marked for export (they beat the step-6 models on held-out maps)",
		 "// and those exported at the user's request (--force); each model's note below has its held-out numbers.",
		 f"// json sha256 {sha}",
		 "// champion_type for dl_next_scores: the SDK's cambc::champion_type order (Cassi 3, Issac 4); round: the game round (1-2000).",
		 "#pragma once", "#include <array>", "#include <vector>", '#include "model_weights.h"', "", "namespace mapintel", "{", "namespace dl_detail", "{",
		 "// relu MLP on standardised inputs, float64, sums in input order (= tools/mapintel/dl/dl_ref.py mlp())",
		 "inline void mlp(const double* x, const double* mean, const double* sd, const int* sz, int nl, const double* W, const double* B, double* out)",
		 "{", "\tdouble a[64], b[64];", "\tfor (int i = 0; i < sz[0]; ++i)", "\t\ta[i] = (x[i] - mean[i]) / sd[i];", "\tint wo = 0, bo = 0;",
		 "\tfor (int l = 0; l < nl; ++l)", "\t{", "\t\tconst int ni = sz[l], no = sz[l + 1];", "\t\tfor (int j = 0; j < no; ++j)", "\t\t{",
		 "\t\t\tdouble v = B[bo + j];", "\t\t\tfor (int i = 0; i < ni; ++i)", "\t\t\t\tv += W[wo + j * ni + i] * a[i];",
		 "\t\t\tb[j] = (l == nl - 1 || v > 0) ? v : 0.0;", "\t\t}", "\t\two += ni * no, bo += no;", "\t\tfor (int j = 0; j < no; ++j)", "\t\t\ta[j] = b[j];",
		 "\t}", "\tfor (int j = 0; j < sz[nl]; ++j)", "\t\tout[j] = a[j];", "}",
		 "// group models: first-layer sums of the per-call inputs xc (input indices p..), in index order (= dl_ref.mlp_const)",
		 "inline void mlp_const(const double* xc, int p, const double* mean, const double* sd, const int* sz, const double* W, double* c)", "{",
		 "\tconst int ni = sz[0];", "\tfor (int j = 0; j < sz[1]; ++j)", "\t{", "\t\tdouble s = 0;", "\t\tfor (int i = p; i < ni; ++i)",
		 "\t\t\ts += W[j * ni + i] * ((xc[i - p] - mean[i]) / sd[i]);", "\t\tc[j] = s;", "\t}", "}",
		 "// one group: its own inputs xg (input indices 0..p-1) and the per-call sums c; the first output (= dl_ref.mlp_split)",
		 "inline double mlp_split(const double* xg, int p, const double* c, const double* mean, const double* sd, const int* sz, int nl, const double* W, const double* B)",
		 "{", "\tdouble a[64], b[64];", "\tfor (int i = 0; i < p; ++i)", "\t\ta[i] = (xg[i] - mean[i]) / sd[i];", "\tint wo = 0, bo = 0;",
		 "\tfor (int l = 0; l < nl; ++l)", "\t{", "\t\tconst int ni = sz[l], no = sz[l + 1], nu = l == 0 ? p : ni;", "\t\tfor (int j = 0; j < no; ++j)", "\t\t{",
		 "\t\t\tdouble v = l == 0 ? B[j] + c[j] : B[bo + j];", "\t\t\tfor (int i = 0; i < nu; ++i)", "\t\t\t\tv += W[wo + j * ni + i] * a[i];",
		 "\t\t\tb[j] = (l == nl - 1 || v > 0) ? v : 0.0;", "\t\t}", "\t\two += ni * no, bo += no;", "\t\tfor (int j = 0; j < no; ++j)", "\t\t\ta[j] = b[j];",
		 "\t}", "\treturn a[0];", "}",
		 "// the same for a 2-layer net with sizes known at compile time (NI inputs, P of them per group, H hidden, 1 output): the loops",
		 "// unroll, which is what costs fuel in this engine; the sums are formed in the same order as mlp_const / mlp_split",
		 "template <int NI, int P, int H>",
		 "inline void mlp2_const(const double* xc, const double* mean, const double* sd, const double* W, double* c)", "{",
		 "\tfor (int j = 0; j < H; ++j)", "\t{", "\t\tdouble s = 0;", "\t\tfor (int i = P; i < NI; ++i)",
		 "\t\t\ts += W[j * NI + i] * ((xc[i - P] - mean[i]) / sd[i]);", "\t\tc[j] = s;", "\t}", "}",
		 "template <int NI, int P, int H>",
		 "inline double mlp2_split(const double* xg, const double* c, const double* mean, const double* sd, const double* W, const double* B)", "{",
		 "\tdouble a[P], h[H];", "\tfor (int i = 0; i < P; ++i)", "\t\ta[i] = (xg[i] - mean[i]) / sd[i];", "\tfor (int j = 0; j < H; ++j)", "\t{",
		 "\t\tdouble v = B[j] + c[j];", "\t\tfor (int i = 0; i < P; ++i)", "\t\t\tv += W[j * NI + i] * a[i];", "\t\th[j] = v > 0 ? v : 0.0;", "\t}",
		 "\tdouble v = B[H];", "\tfor (int j = 0; j < H; ++j)", "\t\tv += W[H * NI + j] * h[j];", "\treturn v;", "}",
		 "} // namespace dl_detail", ""]
	models = J.get("models", {})
	ex = {k: m for k, m in models.items() if m.get("export")}
	if "opening" in ex or "next" in ex:
		L += ["// the inputs every group model shares: compute once (about the cost of first_scores()), reuse for every call",
			  "struct DLInputs", "{", "\tstd::vector<std::array<double, GF_N>> gf;", "\tstd::vector<char> reached;", "\tdouble z[MW_NF];", "};",
			  "inline DLInputs dl_inputs(const Compact& C, const MapView& m, const Features& F)", "{", "\tDLInputs I;",
			  "\tI.gf = group_features(C, m, I.reached);", "\tzfeat(F, I.z);", "\treturn I;", "}", ""]
	def calls(name, m, p, xc, xg):
		"""(const call, per-group call) for model `name` with p per-group inputs."""
		sz = [len(m["mean"])] + [len(b) for _, b in m["layers"]]
		if len(sz) == 3 and sz[2] == 1:
			t = f"<{sz[0]}, {p}, {sz[1]}>"
			return (f"dl_detail::mlp2_const{t}({xc}, DL_{name}_MEAN, DL_{name}_STD, DL_{name}_W, c);",
					f"dl_detail::mlp2_split{t}({xg}, c, DL_{name}_MEAN, DL_{name}_STD, DL_{name}_W, DL_{name}_B)")
		return (f"dl_detail::mlp_const({xc}, {p}, DL_{name}_MEAN, DL_{name}_STD, DL_{name}_SZ, DL_{name}_W, c);",
				f"dl_detail::mlp_split({xg}, {p}, c, DL_{name}_MEAN, DL_{name}_STD, DL_{name}_SZ, DL_{name}_NL, DL_{name}_W, DL_{name}_B)")

	if "opening" in ex:
		m = ex["opening"]
		oc, og = calls("OPEN", m, "GF_N", "I.z", "I.gf[g].data()")
		L += [f"// opening: {m['note']}", "#define MAPINTEL_DL_OPENING 1"] + model_block("OPEN", m) + [
			"inline std::vector<double> dl_opening_scores(const DLInputs& I)", "{",
			"\tstd::vector<double> out(I.gf.size(), -1e300);", "\tdouble c[64];",
			"\t" + oc, "\tfor (std::size_t g = 0; g < I.gf.size(); ++g)",
			"\t\tif (I.reached[g])", "\t\t\tout[g] = " + og + ";",
			"\treturn out;", "}", ""]
	if "next" in ex:
		m = ex["next"]
		nc, ng = calls("NEXT", m, "GF_N + 1", "xc", "x")
		L += [f"// next target: {m['note']}", "#define MAPINTEL_DL_NEXT 1"] + model_block("NEXT", m) + [
			"// prev: the group the body captured last; champion_type: cambc::champion_type order; round: the game round; only: score these",
			"// groups only (the others -1e300): about 1,600 fuel a group, so a game turn scores a candidate list, not all 64 groups",
			"inline std::vector<double> dl_next_scores(const Compact& C, const DLInputs& I, int prev, int champion_type, int round,",
			"\t\t\t\t\t\t\t\t\t\t  const std::vector<int>* only = nullptr)", "{",
			"\tstd::vector<double> out(I.gf.size(), -1e300);",
			"\tif (prev < 0 || prev >= static_cast<int>(I.gf.size()))", "\t\treturn out;",
			"\tdouble xc[14 + MW_NF], c[64], x[GF_N + 1];", "\txc[0] = round / 2000.0;", "\tfor (int k = 0; k < 13; ++k)",
			"\t\txc[1 + k] = k == champion_type ? 1.0 : 0.0;", "\tfor (int i = 0; i < MW_NF; ++i)", "\t\txc[14 + i] = I.z[i];",
			"\t" + nc,
			"\tconst std::size_t n = only ? only->size() : I.gf.size();",
			"\tfor (std::size_t k = 0; k < n; ++k)", "\t{", "\t\tconst auto g = only ? static_cast<std::size_t>((*only)[k]) : k;",
			"\t\tif (g >= I.gf.size() || !I.reached[g])", "\t\t\tcontinue;",
			"\t\tfor (int i = 0; i < GF_N; ++i)", "\t\t\tx[i] = I.gf[g][static_cast<std::size_t>(i)];",
			"\t\tx[GF_N] = detail::box_dist(C.bx[static_cast<std::size_t>(prev)], C.bx[g]) / 100.0;",
			"\t\tout[g] = " + ng + ";", "\t}",
			"\treturn out;", "}", ""]
	if "values" in ex:
		m = ex["values"]
		L += [f"// champion values: {m['note']}", "#define MAPINTEL_DL_VALUES 1"] + model_block("VAL", m) + [
			f"inline constexpr double DL_VAL_W0[12] = {arr(m['w'])};",
			"inline void dl_champion_values(const Features& F, double out[12])", "{", "\tdouble z[MW_NF], o[12];", "\tzfeat(F, z);",
			"\tdl_detail::mlp(z, DL_VAL_MEAN, DL_VAL_STD, DL_VAL_SZ, DL_VAL_NL, DL_VAL_W, DL_VAL_B, o);", "\tfor (int c = 0; c < 12; ++c)",
			"\t\tout[c] = DL_VAL_W0[c] + o[c];", "}", ""]
	L += ["} // namespace mapintel", ""]
	return "\n".join(L)


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--weights", default=os.path.join(ROOT, "experiments/results/mapintel/dl_model/dl_weights.json"))
	ap.add_argument("--out", default=os.path.join(ROOT, "tools/mapintel/cpp/mapintel/dl_weights.h"))
	ap.add_argument("--force", default="", help="comma-separated models to write although the run did not mark them (the user's decision; "
					"the header and the note say so)")
	a = ap.parse_args()
	raw = open(a.weights, "rb").read()
	J = json.loads(raw)
	for k in [x for x in a.force.split(",") if x]:
		m = J.get("models", {}).get(k)
		if m is None:
			raise SystemExit(f"--force {k}: no such model in {a.weights}")
		if not m.get("export"):
			m["export"] = True
			m["note"] = m["note"] + "; below the export rule (the bar + margin), exported at the user's request"
	n = [k for k, m in J.get("models", {}).items() if m.get("export")]
	if not n:
		print("no model is marked for export (none beat the step-6 models): no header written")
		return
	open(a.out, "w").write(header(J, hashlib.sha256(raw).hexdigest()))
	print(f"{a.out}: {', '.join(n)}")


if __name__ == "__main__":
	main()
