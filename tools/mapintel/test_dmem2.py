import dmem2 as D2  # noqa: E402
import export_headers as EH  # noqa: E402
import features as FT  # noqa: E402
import hazards as HZ  # noqa: E402
import mapdata  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ROSTERS = [[8, 4, 3, 0, 9], [11, 1, 2, 6, 5], [10, 7, 3, 9, 1]]  # draft ids; test inputs only (any rosters do)
LIMIT = [1_000_000] + [100_000] * 9


def build(r, nav_always):
	name = f"_mi_dm2_{r}"
	d = os.path.join(ROOT, "bots", name)
	shutil.rmtree(os.path.join(d, "src"), ignore_errors=True)
	os.makedirs(os.path.join(d, "src"))
	shutil.copy(os.path.join(ROOT, "tools/mapintel/cpp/test2/main.cpp"), os.path.join(d, "src", "main.cpp"))
	shutil.copytree(os.path.join(ROOT, "tools/mapintel/cpp/mapintel"), os.path.join(d, "src", "mapintel"))
	shutil.copytree(os.path.join(ROOT, "tools/teamplan/cpp/teamplan"), os.path.join(d, "src", "teamplan"))
	with open(os.path.join(d, "src", "mi_dm2_roster.h"), "w") as f:
		f.write("#pragma once\n// generated by tools/mapintel/test_dmem2.py\n")
		if nav_always:
			f.write("#define MI_DM2_NAV_ALWAYS 1\n")
		f.write(f"#define MI_DM2_R {r}\n")
		f.write("inline constexpr int MI_DM2_ROSTERS[3][5] = { " + ", ".join("{ " + ", ".join(map(str, x)) + " }" for x in ROSTERS) + " };\n")
	res = subprocess.run(["cambc", "build", name, "--release"], cwd=ROOT, capture_output=True, text=True)
	if res.returncode != 0:
		sys.exit(f"{name} build failed:\n" + (res.stdout + res.stderr)[-4000:])
	return name


def run(bot, maps, jobs, tmp, rounds):
	man = os.path.join(tmp, f"man_{bot}.txt")
	with open(man, "w") as f:
		for m in maps:
			f.write(f"{ROOT}/bots/{bot} {ROOT}/bots/{bot} {m} {tmp}/{bot}_{os.path.basename(m)}.repl26a\n")
	subprocess.run(["cambc", "run-batch", man, "--jobs", str(jobs), "--rounds", str(rounds), "--release", "--color", "never"],
				   capture_output=True, text=True)


def member(z, name):
	return z.read(name).decode("utf-8", "replace").replace("\x00", "")


def fnv(b):
	h = 1469598103934665603
	for x in b:
		h = ((h ^ x) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
	return h.to_bytes(8, "big").hex()


def u16(b, o):
	return b[o] | b[o + 1] << 8


def parse(text):
	out = {"C1": [], "C2": [], "C3": None, "IMG": None, "P": None, "E": []}
	for l in text.splitlines():
		t = l.split()
		if l.startswith("MI C1 "):
			out["C1"].append(dict(zip(t[2::2], t[3::2])))
		elif l.startswith("MI C2 "):
			out["C2"].append(dict(zip(t[2::2], t[3::2])))
		elif l.startswith("MI C3 "):
			out["C3"] = [int(x) for x in t[2:]]
		elif l.startswith("MI IMG "):
			out["IMG"] = bytes.fromhex(t[2])
		elif l.startswith("MI P "):
			out["P"] = bytes.fromhex(t[2])
		elif l.startswith("MI E"):
			out["E"].append(l)
	return out


class Ctx:
	"""Everything the twins need for one map and team (cached across the three builds)."""

	def __init__(self, n, M, team, arche, ftw):
		self.M, self.team = M, team
		self.C = CP.Compact(M, team)
		self.CE = CP.Compact(M, 1 - team)
		self.rank = EH.first_rank_py(M, team, ftw, 16) if ftw is not None else []
		z = EH.zfeat_py(FT.compute(M, team), arche)
		self.arch = EH.archetype_py(z, arche)
		self.mode = self.C.tiebreak_mode()
		self.bank_ord = D2.bank_order_py(self.C)
		self.band, self.con = self.C.contested()
		self.anchors = D2.nav_anchor_groups(self.C, self.rank)
		self.arche = arche
		self.nav = None

	def nav_block(self):
		if self.nav is None:
			self.nav = HZ.nav_block(self.M, self.team, self.anchors, self.bank_ord[:3], C=self.C)
		return self.nav


def expected_masks(base):
	"""The fallback cases of the test bot's game turn 3: the found-block mask after each corruption."""
	present = 0
	for k, (idc, off, ln, ver) in enumerate(D2.BLOCKS):
		if D2.Reader(base).block(idc, ver) is not None:
			present |= 1 << k
	drop = [D2.BK["O"], D2.BK["B"], None, D2.BK["K"], D2.BK["E"], D2.BK["N"]]
	return [0 if d is None else present & ~(1 << d) for d in drop], present


def check(name, team, r, M, ctx, out, K, own_full_cache, fails, stats, known_names, fp_hex, nav_always, table_nav, table_dl, dl_open_model):
	tag = f"{name} team {team} r{r}"
	if out["E"]:
		fails.append(f"{tag}: exceptions {out['E'][:2]}")
	if out["IMG"] is None or out["P"] is None or not out["C1"]:
		fails.append(f"{tag}: no output")
		return
	img = out["IMG"]
	side = img[499]
	ts = img[500]
	picks = ROSTERS[(r + side) % 3][:ts]
	eroster = ROSTERS[(r + 1 - side) % 3][:ts]
	types = D2.roster_types(picks)
	got_types = sorted(int(c["type"]) for c in out["C1"])
	if got_types != types:
		fails.append(f"{tag}: roster {got_types} != ours {types} (random picks: a draft turn ran out)")
		return
	R = D2.Reader(img + bytes(512))
	if not R.ok:
		fails.append(f"{tag}: header invalid")
		return
	# twins
	blocks = {}
	team_b = R.block("T", 1)
	own_n = team_b[11] if team_b else 0
	own_mask = (team_b[12] | team_b[13] << 8) if team_b else 0
	own_types = [t for t in range(D2.DM2_NBODY) if own_mask >> t & 1]
	own = None
	if R.block("O", 1) is not None:
		own = D2.build_own(D2.own_groups(ctx.C, M, K.p), own_types, K)
		blocks["O"] = own.b
	blocks["T"] = D2.build_team(ctx.mode, types, own, K.p.capture_mode)
	bodies, plan = ctx.C.plan1(picks, ctx.rank or None)
	bb, rp = D2.econ_body()
	blocks["B"] = D2.build_body(types, K, bodies, plan, bb, rp)
	ne_cont = img[503]
	blocks["C"] = D2.build_cont(K, eroster[:ne_cont], types)
	blocks["K"] = D2.build_code(ctx.C, ctx.con, own, ctx.bank_ord)
	if R.block("E", 1) is not None:
		blocks["E"] = D2.build_enemy(ctx.CE, K, eroster[:img[497]])
	nb = R.block("N", 1)
	if nb is not None:
		if nb[61] == HZ.NAV_SRC_TABLE:
			want = bytearray(bytes.fromhex(table_nav[str(team)]))
			want[61] = HZ.NAV_SRC_TABLE
			blocks["N"] = bytes(want)
			if nav_always:
				fails.append(f"{tag}: NAV copied in the compute build")
		else:
			blocks["N"] = ctx.nav_block()
			stats["nav_computed"] += 1
	elif img[1017] != 0 or (ctx.M.name in known_names and r != 0):
		fails.append(f"{tag}: NAV missing (complete on turn {img[1016]}, source {img[1017]})")
	# L: the DL outputs (known maps: the catalog's tables, dl_tables.py; unknown maps: dl_ref's opening ranking when the draft computed it)
	dlc = table_dl
	if dlc and dlc.get("open"):
		G = len(M.groups)
		nexte = bytes.fromhex(dlc["next"][str(team)])[:13 * G * 2] if dlc.get("next") else None
		blocks["L"] = D2.build_dl(bytes.fromhex(dlc["open"][str(team)]), 2, nexte, G, types, bodies, plan, dlc["split"], dlc["rounds"][0], dlc["rounds"][1])
		stats["dl_known"] += 1
	elif R.block("L", 1) is not None or (D2.BK["L"] < D2.DM2_NTOC and img[D2.DM2_TOC + 8 * D2.BK["L"]] == ord("L")):
		if dl_open_model is None:
			fails.append(f"{tag}: an L block without dl_weights.h's opening model")
		else:
			sys.path.insert(0, os.path.join(HERE, "dl"))
			import dl_ref as DLR
			r16 = DLR.rank(DLR.opening_scores(M, team, ctx.arche, dl_open_model), 16)
			blocks["L"] = D2.build_dl(bytes(r16 + [255] * (16 - len(r16))), 1, None, 0, types, bodies, plan, 571, 329, 849)
			stats["dl_computed"] += 1
	blocks["D"] = R.block("D", 1)
	if blocks["D"] is None:
		fails.append(f"{tag}: DEBUG missing")
		return
	known = ctx.M.name in known_names
	mblk = CP.pack(ctx.C, int(fp_hex, 16), picks, known, ctx.arch, ctx.rank or None)
	# per block
	for idc, want in blocks.items():
		if idc == "L":
			continue  # at 864, past the printed 0-511: the whole-image hash below covers it (and its TOC entry is compared)
		gotb = R.block(idc, 1) if idc != "D" else blocks["D"]
		if gotb is None:
			fails.append(f"{tag}: block {idc} missing")
		elif bytes(gotb) != bytes(want):
			i = next(i for i in range(len(want)) if gotb[i] != want[i])
			fails.append(f"{tag}: block {idc} byte {i}: C++ {bytes(gotb[max(0, i - 2):i + 6]).hex()} != Python {bytes(want[max(0, i - 2):i + 6]).hex()}")
		else:
			stats["blocks"] += 1
	# the whole image: the twins' blocks + the M block + the test bytes (436-511, 1000-1023) as the champions printed them
	full = bytearray(D2.DM2_SIZE)
	full[436:512] = img[436:512]
	full[1000:1024] = out["P"]
	blocks["M"] = mblk
	want_img = D2.image(blocks, img[2], bytes(full))
	if want_img[:512] != img:
		i = next(i for i in range(512) if want_img[i] != img[i])
		fails.append(f"{tag}: image byte {i} (header / TOC): C++ {img[i]} != Python {want_img[i]}")
	h = {c["hash"] for c in out["C1"]}
	if len(h) != 1:
		fails.append(f"{tag}: champions read different images {sorted(h)}")
	elif h.pop() != fnv(want_img):
		fails.append(f"{tag}: the image read in the game differs from the twins' image (M block, the tail or the prefix rule)")
	else:
		stats["images"] += 1
	# coexistence: the M entry, the v1 reader
	e = img[D2.DM2_TOC + 8 * D2.BK["M"]:D2.DM2_TOC + 8 * D2.BK["M"] + 8]
	if e[0] != ord("M") or u16(e, 2) != 512 or u16(e, 4) != 352 or e[7] != 1:
		fails.append(f"{tag}: TOC M entry {e.hex()}")
	if any(c["v1"] != "1" or c["v1hash"] != fnv(mblk) for c in out["C1"]):
		fails.append(f"{tag}: the v1 reader (dmem_get) did not read compact.pack's block")
	if out["P"][0] != 0xAB:
		fails.append(f"{tag}: byte 1000 = {out['P'][0]} after the 1,000-byte write (prefix rule)")
	if img[2] & D2.DM2_FINAL == 0:
		fails.append(f"{tag}: the last write is not final")
	# fallback
	masks, present = expected_masks(want_img)
	if out["C3"] != masks:
		fails.append(f"{tag}: fallback masks {out['C3']} != {masks}")
	# in-game OWN recompute: every body the same table, equal to the twin for the full roster
	c2 = out["C2"]
	key = (name, team, tuple(types))
	if key not in own_full_cache:
		own_full_cache[key] = D2.build_own(D2.own_groups(ctx.C, M, K.p), types, K).b
	want_own = fnv(own_full_cache[key])
	if not c2 or len({c["own"] for c in c2}) != 1 or any(c["ok"] != "1" for c in c2):
		fails.append(f"{tag}: in-game OWN recompute {[c.get('own') for c in c2]}")
	elif c2[0]["own"] != want_own:
		fails.append(f"{tag}: in-game OWN {c2[0]['own']} != the twin's {want_own}")
	else:
		stats["own_recompute"] += 1
		stats["own_game_fuel"] = max(stats["own_game_fuel"], max(int(c["fuel"]) for c in c2))
		stats["own_game_turns"] = max(stats.get("own_game_turns", 0), max(int(c["turns"]) for c in c2))


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--maps", default="maps/official/*.map26a")
	ap.add_argument("--perturbed", type=int, default=12)
	ap.add_argument("--jobs", type=int, default=4)
	ap.add_argument("--rounds", type=int, default=8)
	a = ap.parse_args()
	fails = []
	bots = [build(0, True), build(1, False), build(2, False)]
	maps = sorted(glob.glob(os.path.join(ROOT, a.maps)))
	tmp = tempfile.mkdtemp(prefix="mi_dm2_")
	for b in bots:
		run(b, maps, a.jobs, tmp, a.rounds)
	arche = json.load(open(os.path.join(ROOT, "maps/catalog/archetypes.json")))
	fp_ = os.path.join(ROOT, "experiments/results/mapintel/first_targets/weights.json")
	ftw = json.load(open(fp_)) if os.path.exists(fp_) else None
	fps = dict(l.split()[:2] for l in open(os.path.join(ROOT, "experiments/results/mapintel/dump/fingerprints.txt")))
	known_names = set(fps)
	K = D2.Kits13()
	stats = {"blocks": 0, "images": 0, "own_recompute": 0, "own_game_fuel": 0, "nav_computed": 0, "dl_known": 0, "dl_computed": 0}
	dlj = os.path.join(ROOT, "tools/mapintel/cpp/mapintel/dl_weights.h")
	dl_open_model = None
	if os.path.exists(dlj) and "#define MAPINTEL_DL_OPENING 1" in open(dlj).read():
		sha = next((l.split()[3] for l in open(dlj) if l.startswith("// json sha256 ")), "")
		for f in sorted(glob.glob(os.path.join(ROOT, "experiments/results/mapintel/dl_model*/dl_weights.json"))):
			import hashlib
			if hashlib.sha256(open(f, "rb").read()).hexdigest() == sha:
				dl_open_model = json.load(open(f))["models"]["opening"]
	fuel = {"turn1": [], "later_max": 0, "last_left_min": 10 ** 9, "parts": {}, "own": 0, "enemy": 0, "nav_turns": []}
	own_cache = {}
	per_map = []

	def one(name, M, ctxs, bot, r, rp, nav_always, table_nav, fp_hex, table_dl=None):
		if not os.path.exists(rp):
			fails.append(f"{name} r{r}: no replay")
			return
		z = zipfile.ZipFile(rp)
		for team, f in ((0, "team-a"), (1, "team-b")):
			out = parse(member(z, f + ".stdout"))
			if team not in ctxs:
				ctxs[team] = Ctx(name, M, team, arche, ftw)
			check(name, team, r, M, ctxs[team], out, K, own_cache, fails, stats, known_names, fp_hex, nav_always, table_nav, table_dl, dl_open_model)
			d = z.read(f + ".fuel")
			k = (len(d) - 12) // 8
			img, P = out["IMG"], out["P"]
			if img is None or P is None:
				continue
			ts = img[500]
			# the fuel stream: 8 limits, then every turn of this team in order: its ts draft turns, then the game turns
			used = [x // 256 for x in struct.unpack(f"<{k}Q", d[12:12 + 8 * k])[8:8 + ts]]
			for t, u in enumerate(used):
				if u >= LIMIT[t]:
					fails.append(f"{name} team {team} r{r}: draft turn {t + 1} used {u} (limit {LIMIT[t]}): it ran out")
			fuel["turn1"].append((used[0], name, team, r))
			fuel["later_max"] = max(fuel["later_max"], max(used[1:ts]) if ts > 1 else 0)
			last = min(ts, 5) - 1
			fuel["last_left_min"] = min(fuel["last_left_min"], u16(img, 436 + 12 * last + 10) * 16)
			for t in range(min(ts, 5)):
				fuel["own"] = max(fuel["own"], u16(img, 436 + 12 * t + 6) * 16)
				fuel["enemy"] = max(fuel["enemy"], u16(img, 436 + 12 * t + 8) * 16)
			names = ["kits", "bank+rally", "M", "TEAM+CODE", "NAV (all turns)", "OWN turn 1", "ENEMY turn 1"]
			for i, nm in enumerate(names):
				v = u16(P, 2 + 2 * i) * 16
				if v > fuel["parts"].get(nm, (0, ""))[0]:
					fuel["parts"][nm] = (v, name)
			if nav_always or name not in known_names:
				fuel["nav_turns"].append(P[16])
			if team == 0 and r == 1:
				per_map.append((used[0], name, [u16(P, 2 + 2 * i) * 16 for i in range(7)]))

	for m in maps:
		name = os.path.splitext(os.path.basename(m))[0]
		M = mapdata.load(name)
		cat = json.load(open(os.path.join(ROOT, "maps/catalog", name + ".json")))
		ctxs = {}
		for r, b in enumerate(bots):
			one(name, M, ctxs, b, r, os.path.join(tmp, f"{b}_{os.path.basename(m)}.repl26a"), r == 0, cat.get("nav"), fps[name], cat.get("dl"))
	if a.perturbed:
		pdir = tempfile.mkdtemp(prefix="mi_dm2_pert_")
		pm = []
		for i, m in enumerate(maps[: a.perturbed]):
			out = os.path.join(pdir, f"zz_dm2pert{i:02d}_{os.path.basename(m)}")
			res = subprocess.run(["node", os.path.join(ROOT, "tools/mapgen/perturb.mjs"), m, out, "--seed", str(31 + i)], capture_output=True, text=True)
			if res.returncode == 0 and os.path.exists(out):
				pm.append(out)
		dump = tempfile.mkdtemp(prefix="mi_dm2_pdump_")
		subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools/mapintel/dump_maps.py"), "--maps", ",".join(pm), "--out", dump],
					   capture_output=True, text=True)
		run(bots[1], pm, a.jobs, tmp, a.rounds)
		for m in pm:
			name = os.path.splitext(os.path.basename(m))[0]
			if not os.path.exists(os.path.join(dump, name + ".txt")):
				fails.append(f"{name}: no dump")
				continue
			M = mapdata.load(name, dump)
			M.name = name
			one(name, M, {}, bots[1], 1, os.path.join(tmp, f"{bots[1]}_{os.path.basename(m)}.repl26a"), False, None, M.fingerprint)
		stats["perturbed"] = len(pm)
	t1 = sorted(fuel["turn1"], reverse=True)
	print(f"maps: {len(maps)} official x 2 teams x 3 builds" + (f" + {stats.get('perturbed', 0)} perturbed (unknown) x 2 teams" if a.perturbed else "")
		  + f": {stats['blocks']} blocks bit-equal to the twins, {stats['images']} whole images equal (every champion), "
		  f"{stats['own_recompute']} in-game OWN recomputes equal, NAV computed and equal on {stats['nav_computed']} map-teams, "
		  f"the L block (DL) from the known-map tables on {stats['dl_known']} and computed in the draft on {stats['dl_computed']}")
	print(f"fuel, draft turn 1 (limit 1,000,000, the engine's count): worst {t1[0][0] if t1 else 0} ({t1[0][1] if t1 else ''}); "
		  f"later turns at most {fuel['later_max']} (limit 100,000); the last turn left at least {fuel['last_left_min']} before its write")
	print("fuel, blocks (max): " + ", ".join(f"{k} {v[0]} ({v[1]})" for k, v in fuel["parts"].items())
		  + f"; OWN in a draft turn {fuel['own']}, ENEMY {fuel['enemy']}; OWN recompute in the game {stats['own_game_fuel']} in all, over at most {stats.get('own_game_turns', 0)} game turns (floor 20,000 a turn)")
	if fuel["nav_turns"]:
		nt = fuel["nav_turns"]
		print(f"NAV computed in the draft: complete on turn 1 on {sum(1 for x in nt if x == 1)}, later on {sum(1 for x in nt if x > 1)}, "
			  f"never on {sum(1 for x in nt if x == 0)} of {len(nt)} map-teams")
	per_map.sort(reverse=True)
	print("heaviest first turns (roster build 1, team A): " + "; ".join(f"{n} {u}" for u, n, _ in per_map[:5]))
	print("FAILURES:\n  " + "\n  ".join(fails[:40]) if fails else "all checks passed")
	sys.exit(1 if fails else 0)


if __name__ == "__main__":
	main()
