#!/usr/bin/env python3
"""Engine tests of draft memory version 2 (docs/DRAFT_MEMORY.md 8) through the test bot tools/mapintel/cpp/test2/main.cpp.

    python3 -I tools/mapintel/test_dmem2.py [--maps 'maps/official/*.map26a'] [--perturbed 12] [--jobs 4] [--rounds 4]

Builds bots/_mi_dm2_0, _1, _2 (git-ignored): the test bot + tools/mapintel/cpp/mapintel/ + tools/teamplan/cpp/teamplan/, one per roster
index r (team side 0 drafts roster r, side 1 roster r + 1, of ROSTERS below; build 0 also computes NAV on known maps, to compare it with
the table). Plays every map with both teams as the same build for a few rounds and checks, per map and team:
  * the round trip: every block the draft wrote equals the Python twins (dmem2.py, hazards.py, compact.py) byte for byte: TEAM, OWN,
    BODY, CONT, CODE, ENEMY, NAV, the header and the table of contents; the M block (mapintel's v1 block at 512) equals compact.pack;
    the whole 1,024-byte image every champion read has the same hash, and it equals the image rebuilt from the twins;
  * coexistence: the TOC's M entry points at 512 / 352 bytes and the old v1 reader (dmem.h dmem_get) still reads the block;
  * the prefix rule: the draft's last write is the whole image with byte 1000 = 0xAB, then a 1,000-byte write: every champion reads
    0xAB at 1000 (the tail is kept) and the rest unchanged;
  * fallback: six corrupted copies (OWN data, BODY version, header magic, CODE offset past the end, ENEMY not valid, NAV missing): the
    reader finds exactly the other blocks, and nothing on a bad header; no exception anywhere;
  * the in-game OWN recompute (game turn 2, every body): the same table in every body, equal to the twin's OWN for the full roster;
  * fuel: every draft turn within its limit (the engine's own count), the five picks are ours on every map (none random), and the
    turn-by-turn costs of the blocks (printed);
  * N perturbed copies (unknown maps): the same checks, with NAV computed in the draft.
Exit status 1 on any failure."""
import argparse, glob, json, os, shutil, struct, subprocess, sys, tempfile, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
