#!/usr/bin/env python3
"""Two-action decision model (T-learner) on the contact dataset (agent ml2, session 13).

usage: python3 -I tools/ml/ml2_tlearner.py DATA.npz [--lam 1.5] [--export OUT.h]

Rows: contact rows where the body either hit a champion next round (action "hit") or stepped away from the nearest enemy
(action "away"), all teams, duplicates and censored ends dropped. Four logistic models, each fit on the rows of one action:
P(die8 | x, hit), P(die8 | x, away), P(kill8 | x, hit), P(kill8 | x, away) (out-of-fold predictions, games kept whole).
Value of an action = P(kill8) - lam x P(die8). Recommended action = argmax. Prints, by recommendation and by what the body
actually did, the real kill8 / die8 rates (a direct-method check: when the recommendation and the action agree, outcomes
should beat the rows where they disagree), and the share of our bodies' rows where the recommendation differs from the
action taken. --export writes the four weight vectors (raw features, dataset order) for the bot.
"""
import json
import sys

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold


def main():
	a = sys.argv[1:]
	lam, export = 1.5, None
	if '--lam' in a:
		i = a.index('--lam'); lam = float(a[i + 1]); del a[i:i + 2]
	if '--export' in a:
		i = a.index('--export'); export = a[i + 1]; del a[i:i + 2]
	d = np.load(a[0])
	X, Y, M = d['X'], d['Y'], d['M']
	F, L = list(d['features']), list(d['labels'])
	G = json.loads(str(d['games']))
	keep = np.array([not G[g].get('dup') for g in M[:, 0]]) & (Y[:, L.index('censored')] == 0)
	X, Y, M = X[keep], Y[keep], M[keep]
	hit = Y[:, L.index('act_hit1')] > 0
	away = (Y[:, L.index('act_away1')] > 0) & ~hit
	sel = hit | away
	X, Y, M, hit = X[sel], Y[sel], M[sel], hit[sel]
	cols = [i for i, f in enumerate(F) if f != 'bush4']
	Xc = np.hstack([X[:, cols], (M[:, 3:4] == 1).astype(np.float32)])  # + our-bot flag
	mu, sd = Xc.mean(0), Xc.std(0) + 1e-6
	Z = (Xc - mu) / sd
	g = M[:, 0]
	die, kill = Y[:, 1], Y[:, 2]
	us = M[:, 3] == 1
	pred = {}
	for lab, yv in (('die', die), ('kill', kill)):
		for act, am in (('hit', hit), ('away', ~hit)):
			p = np.zeros(len(yv))
			for tr, te in GroupKFold(5).split(Z, yv, g):
				t = tr[am[tr]]
				m = LogisticRegression(C=0.5, max_iter=3000).fit(Z[t], yv[t])
				p[te] = m.predict_proba(Z[te])[:, 1]
			pred[(lab, act)] = p
	v_hit = pred[('kill', 'hit')] - lam * pred[('die', 'hit')]
	v_away = pred[('kill', 'away')] - lam * pred[('die', 'away')]
	rec_hit = v_hit > v_away
	print(f'rows {len(Z)} (us {us.sum()}), hit {hit.mean():.2f}; lam {lam}')
	for side, s in (('us', us), ('them', ~us), ('all', np.ones(len(us), bool))):
		print(f'== {side}: recommendation hit {rec_hit[s].mean():.2f}; agrees with the action {np.mean(rec_hit[s] == hit[s]):.2f}')
		for r in (True, False):
			for act in (True, False):
				m = s & (rec_hit == r) & (hit == act)
				if m.sum():
					val = kill[m].mean() - lam * die[m].mean()
					print(f'   rec {"hit " if r else "away"} did {"hit " if act else "away"}: rows {m.sum():6d} kill8 {kill[m].mean():.3f} die8 {die[m].mean():.3f} value {val:+.3f}')
	if export:
		names = [F[c] for c in cols] + ['us']
		with open(export, 'w') as fo:
			fo.write(f'// generated by tools/ml/ml2_tlearner.py: P(label | x, action) logistic weights on raw features (dataset order), us = 1 folded in\n')
			for lab, yv in (('DIE', die), ('KILL', kill)):
				for act, am in (('HIT', hit), ('AWAY', ~hit)):
					m = LogisticRegression(C=0.5, max_iter=3000).fit(Z[am], yv[am])
					w = m.coef_[0] / sd
					b = m.intercept_[0] - float((m.coef_[0] * mu / sd).sum()) + w[-1]
					full = np.zeros(len(F))
					for j, c in enumerate(cols):
						full[c] = w[j]
					fo.write(f'constexpr float ML2_T_B_{lab}_{act} = {b:.6e}f;\n')
					fo.write(f'constexpr float ML2_T_W_{lab}_{act}[{len(F)}] = {{ ' + ', '.join(f'{x:.6e}f' for x in full) + ' };\n')
		print('exported', export, 'features', len(names))


if __name__ == '__main__':
	main()
