#!/usr/bin/env python3
"""Opponent family 2 of the teamplan batteries (TEAMPLAN.md section 9): GOD v10 playing the strong teams' roster of each map.

    python3 -I tools/teamplan/make_forced_v10.py [--name _tp_v10F] [--slot 0]

bots/<name> = bots/god/src + mapintel's force_roster.h / fingerprint.h (read only, copied) + mi_roster.h with roster slot --slot of
tools/mapintel/data/battery_rosters.json per official map (slot 0 = the roster with the most strong-team games: LEARNED), and a
call of mapintel::forced_pick() at the top of v10's draft turn. Maps without a table entry fall back to v10's own draft."""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PICK_NAMES = ["Ryth", "Vesper Vale", "Vendetta", "Cassi & Issac", "Stellar", "Prism", "Marcella", "Willow", "Ren", "Varg", "Tavi", "Heart of Ruin"]


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--name", default="_tp_v10F")
	ap.add_argument("--slot", type=int, default=0)
	a = ap.parse_args()
	d = os.path.join(ROOT, "bots", a.name)
	shutil.rmtree(d, ignore_errors=True)
	os.makedirs(d)
	src = os.path.join(d, "src")
	shutil.copytree(os.path.join(ROOT, "bots", "god", "src"), src)
	gi = os.path.join(ROOT, "bots", "legend", ".gitignore")
	if os.path.exists(gi):
		shutil.copy(gi, d)
	os.makedirs(os.path.join(src, "mapintel"))
	for h in ("force_roster.h", "fingerprint.h"):
		shutil.copy(os.path.join(ROOT, "tools", "mapintel", "cpp", "mapintel", h), os.path.join(src, "mapintel", h))
	R = json.load(open(os.path.join(ROOT, "tools", "mapintel", "data", "battery_rosters.json")))
	lines = []
	for n in sorted(R["maps"]):
		e = R["maps"][n]
		r = e["rosters"][a.slot]
		picks = r["picks"]
		lines.append(f"\t{{ 0x{e['fingerprint']}ull, {len(picks)}, {{ {', '.join(map(str, picks + [0] * (5 - len(picks))))} }} }}, /* {n}: "
					 + ", ".join(PICK_NAMES[p] for p in picks) + f" ({r['origin']}) */")
	open(os.path.join(src, "mapintel", "mi_roster.h"), "w").write(
		f"// generated by tools/teamplan/make_forced_v10.py: roster slot {a.slot} of tools/mapintel/data/battery_rosters.json\n"
		"#define MI_ROSTER_ENTRIES \\\n" + " \\\n".join(lines) + "\n")
	p = os.path.join(src, "draft.cpp")
	s = open(p).read()
	old_inc = '#include "params.h"\n'
	old_fn = "void play_draft_pick()\n{\n"
	if s.count(old_inc) < 1 or s.count(old_fn) != 1:
		sys.exit("draft.cpp changed: the forced-roster hook does not apply")
	s = s.replace(old_inc, old_inc + '#include "mapintel/force_roster.h"\n', 1)
	s = s.replace(old_fn, old_fn + "\tif (const int fp = mapintel::forced_pick(); fp >= 0)\n\t{\n\t\tnote_pick(static_cast<D>(fp));\n\t\treturn;\n\t}\n", 1)
	open(p, "w").write(s)
	r = subprocess.run(["cambc", "build", a.name, "--release"], cwd=ROOT, capture_output=True, text=True)
	if r.returncode != 0:
		sys.exit("build failed:\n" + (r.stdout + r.stderr)[-3000:])
	print(f"bots/{a.name} ready: v10 with roster slot {a.slot} forced on {len(lines)} maps")


if __name__ == "__main__":
	main()
